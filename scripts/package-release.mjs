import { mkdir, cp, readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { SOURCE_FILES } from './source-files.mjs';
const cwd = resolve(import.meta.dirname, '..');
const run = (cmd,args) => { const p = spawnSync(cmd,args,{cwd,stdio:'inherit'}); if(p.status !== 0) throw new Error(`${cmd} failed`); };
if (!process.argv.includes('--draft')) run(process.execPath,['scripts/check-release.mjs']);
run(process.execPath,['scripts/build-site.mjs']);
run(process.execPath,['node_modules/@angular/cli/bin/ng.js','build']);
const version = JSON.parse(await readFile(resolve(cwd,'package.json'),'utf8')).version;
const stamp = new Date().toISOString().replace(/[:.]/g,'-');
const out = resolve(cwd,'releases',`${version}-${stamp}`);
await mkdir(out,{recursive:true});
const common = SOURCE_FILES;
const source = resolve(out,'beergame-source.tar.gz');
run('tar',['-czf',source,'--exclude=.env','--exclude=*.pem','--exclude=*.key','--exclude=*.log',...common]);
const runtime = resolve(out,'runtime'); await mkdir(runtime,{recursive:true});
for (const path of ['server','dist','LICENSE','docs','site.config.json']) await cp(resolve(cwd,path),resolve(runtime,path),{recursive:true});
await cp(resolve(cwd,'node_modules/ws'),resolve(runtime,'node_modules/ws'),{recursive:true,dereference:true});
await writeFile(resolve(runtime,'START.txt'),'Node.js 24: set NODE_ENV=production, PUBLIC_ORIGIN=https://beergame.io, HOST=127.0.0.1 and PORT=8787, then node server/index.mjs. Place behind HTTPS reverse proxy. See docs/DEPLOYMENT.md. Default indexing is off. Includes ws with its upstream license. MCP runs separately.\n');
const hosting = resolve(out,'beergame-hosting.tar.gz');
run('tar',['-czf',hosting,'-C',runtime,'.']);
const mcp = resolve(out,'beergame-mcp.tar.gz');
run('tar',['-czf',mcp,'mcp','package.json','pnpm-lock.yaml','pnpm-workspace.yaml','.npmrc','LICENSE','docs']);
const hashes = [];
for (const file of [source,hosting,mcp]) hashes.push(`${createHash('sha256').update(await readFile(file)).digest('hex')}  ${file.split(/[\\/]/).at(-1)}`);
await writeFile(resolve(out,'SHA256SUMS.txt'),hashes.join('\n')+'\n');
await writeFile(resolve(out,'RELEASE-STATUS.txt'),process.argv.includes('--draft') ? 'DRAFT PACKAGES — resolve site configuration and pass release:check before public deployment.\n' : 'Metadata checks passed. Complete the deployment checklist before publication.\n');
console.log(`Packages written to ${out}`);
